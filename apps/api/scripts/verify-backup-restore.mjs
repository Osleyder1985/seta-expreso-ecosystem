import pg from 'pg';
const { Client } = pg;
const client = new Client({ connectionString: process.env.DATABASE_URL });
await client.connect();
const marker = 'backup-restore-' + Date.now();
await client.query('CREATE TABLE IF NOT EXISTS public._backup_restore_probe (id text primary key, created_at timestamptz not null default now())');
await client.query('INSERT INTO public._backup_restore_probe(id) VALUES ($1)', [marker]);
const result = await client.query('SELECT id FROM public._backup_restore_probe WHERE id = $1', [marker]);
if (result.rowCount !== 1) throw new Error('Backup/restore probe insert failed');
console.log(JSON.stringify({ protocol: 'postgres-backup-restore-probe-v1', marker, sourceData: 'PASS' }));
await client.end();
